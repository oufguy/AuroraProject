BOOL M_SceneSerializer::Save(const FilePath &scenePath, const String &sceneName) {
    std::ostringstream ss;
    ss << "# ============================================================================\n";
    ss << "# Aurora Engine World Scene File (.scene)\n";
    ss << "# Auto-generated by M_SceneSerializer / Aurora Editor\n";
    ss << "# ============================================================================\n\n";

    auto &entities = M_World::Get_Entities();
    ss << "[Scene]\n";
    ss << "Name = " << sceneName << "\n";
    ss << "EntityCount = " << entities.size() << "\n\n";

    INT index = 0;
    for (const auto &ent : entities) {
        if (!ent) continue;

        ss << "[Entity_" << index++ << "]\n";

        String typeStr = "StaticMesh";
        if (ent->Type == EntityType::Character)   typeStr = "Character";
        else if (ent->Type == EntityType::Camera) typeStr = "Camera";
        else if (ent->Type == EntityType::DynamicMesh) typeStr = "DynamicMesh";

        ss << "Type = " << typeStr << "\n";

        // Mesh and name
        String meshPath = "";
        if (auto *sm = ent->As<C_StaticMesh>()) {
            meshPath = sm->Mesh.FilePath;
        } else if (auto *ch = ent->As<C_Character>()) {
            meshPath = ch->Mesh.FilePath;
        }

        ss << "Mesh = " << meshPath << "\n";
        ss << "Position = " << ent->Position.x << ", " << ent->Position.y << ", " << ent->Position.z << "\n";
        ss << "Rotation = " << ent->Rotation.x << ", " << ent->Rotation.y << ", " << ent->Rotation.z << "\n";

        COLOR col = COLOR_WHITE;
        if (auto *sm = ent->As<C_StaticMesh>()) col = sm->Color;
        else if (auto *ch = ent->As<C_Character>()) col = ch->Color;

        ss << "Color = " << static_cast<int>(col.r) << ", "
                         << static_cast<int>(col.g) << ", "
                         << static_cast<int>(col.b) << ", "
                         << static_cast<int>(col.a) << "\n";

        // Material
        MaterialParameters mat = M_Material::Create_Matte(col);
        if (auto *sm = ent->As<C_StaticMesh>()) mat = sm->Material;
        else if (auto *ch = ent->As<C_Character>()) mat = ch->Material;

        String matStr = "Matte";
        if (mat.bUnlit) matStr = "Unlit";
        else if (mat.Shininess > 40.0f) matStr = "Metallic";

        ss << "Material = " << matStr << "\n";
        ss << "Roughness = " << mat.Shininess << "\n";

        // Collision
        String collStr = "BlockAll";
        if (ent->Profile == CollisionProfile::NoCollision) collStr = "NoCollision";
        else if (ent->Profile == CollisionProfile::Entity) collStr = "Entity";
        else if (ent->Profile == CollisionProfile::Trigger) collStr = "Trigger";

        ss << "Collision = " << collStr << "\n\n";
    }

    return M_File::Write(scenePath, ss.str(), /*bOverWrite=*/true);
}

Array<SceneEntityRecord> M_SceneSerializer::Parse_Records(const FilePath &scenePath) {
    String text = M_File::Open(scenePath);
    if (text.empty()) return {};

    Array<SceneEntityRecord> records;
    std::istringstream stream(text);
    String line;
    SceneEntityRecord current{};
    BOOL inEntity = false;

    while (std::getline(stream, line)) {
        // Trim whitespace
        while (!line.empty() && (line.back() == '\r' || line.back() == ' ' || line.back() == '\t')) line.pop_back();
        size_t start = line.find_first_not_of(" \t");
        if (start == String::npos) continue;
        line = line.substr(start);

        if (line.empty() || line[0] == '#') continue;

        if (line.front() == '[' && line.back() == ']') {
            if (inEntity && !current.Type.empty()) {
                records.push_back(current);
                current = SceneEntityRecord{};
            }
            if (line.rfind("[Entity_", 0) == 0) {
                inEntity = true;
            } else {
                inEntity = false;
            }
            continue;
        }

        if (!inEntity) continue;

        size_t eq = line.find('=');
        if (eq == String::npos) continue;

        String key = line.substr(0, eq);
        String val = line.substr(eq + 1);
        while (!key.empty() && key.back() == ' ') key.pop_back();
        size_t vstart = val.find_first_not_of(" \t");
        if (vstart != String::npos) val = val.substr(vstart);

        if (key == "Type") current.Type = val;
        else if (key == "Mesh") current.MeshPath = val;
        else if (key == "Position") {
            float x = 0, y = 0, z = 0;
            std::sscanf(val.c_str(), "%f, %f, %f", &x, &y, &z);
            current.Position = { x, y, z };
        }
        else if (key == "Rotation") {
            float p = 0, y = 0, r = 0;
            std::sscanf(val.c_str(), "%f, %f, %f", &p, &y, &r);
            current.Rotation = { p, y, r };
        }
        else if (key == "Color") {
            int cr = 255, cg = 255, cb = 255, ca = 255;
            std::sscanf(val.c_str(), "%d, %d, %d, %d", &cr, &cg, &cb, &ca);
            current.Color = COLOR(static_cast<BYTE>(cr), static_cast<BYTE>(cg), static_cast<BYTE>(cb), static_cast<BYTE>(ca));
        }
        else if (key == "Material") current.MaterialType = val;
        else if (key == "Roughness") current.Roughness = std::stof(val);
        else if (key == "Collision") current.Collision = val;
    }

    if (inEntity && !current.Type.empty()) {
        records.push_back(current);
    }

    return records;
}

BOOL M_SceneSerializer::Load(const FilePath &scenePath) {
    Array<SceneEntityRecord> records = Parse_Records(scenePath);
    if (records.empty()) {
        LOG(Warn, LogLevel::Developer, "M_SceneSerializer::Load -> No entities found in [{}]", scenePath.string());
        return false;
    }

    M_World::Clear();

    for (const auto &rec : records) {
        if (rec.Type == "Character") {
            auto *ch = M_World::Spawn<C_Character>();
            ch->Position = rec.Position;
            ch->Rotation = rec.Rotation;
            ch->Color    = rec.Color;
            if (!rec.MeshPath.empty()) {
                ch->Mesh = M_Asset::Load_Mesh(rec.MeshPath);
            }
            if (rec.MaterialType == "Metallic") {
                ch->Material = M_Material::Create_Metallic(rec.Color, rec.Roughness);
            } else {
                ch->Material = M_Material::Create_Matte(rec.Color);
            }
            ch->Set_CollisionProfile(CollisionProfile::Entity);
        }
        else {
            auto *sm = M_World::Spawn<C_StaticMesh>();
            sm->Position = rec.Position;
            sm->Rotation = rec.Rotation;
            sm->Color    = rec.Color;
            if (!rec.MeshPath.empty()) {
                sm->Mesh = M_Asset::Load_Mesh(rec.MeshPath);
            }
            if (rec.MaterialType == "Metallic") {
                sm->Material = M_Material::Create_Metallic(rec.Color, rec.Roughness);
            } else {
                sm->Material = M_Material::Create_Matte(rec.Color);
            }

            if (rec.Collision == "NoCollision") sm->Set_CollisionProfile(CollisionProfile::NoCollision);
            else if (rec.Collision == "Trigger") sm->Set_CollisionProfile(CollisionProfile::Trigger);
            else sm->Set_CollisionProfile(CollisionProfile::BlockAll);
        }
    }

    LOG(Info, LogLevel::Core, "M_SceneSerializer::Load -> Loaded [{}] ({} entities spawned)", scenePath.string(), records.size());
    return true;
}

