Array<BYTE> E_XORGenerator::Generate_Key(const String &passphrase) {
    Array<BYTE> key(32); // 256 bits

    // Seed state using 64-bit FNV-1a hash of the passphrase
    UINT64 h1 = 0xcbf29ce484222325ULL;
    UINT64 h2 = 0x100000001b3ULL;

    for (unsigned char c : passphrase) {
        h1 ^= c;
        h1 *= 0x100000001b3ULL;
        h2 = (h2 ^ c) + 0x9e3779b97f4a7c15ULL;
    }

    // SplitMix64 pseudo-random generation to fill 32 bytes
    for (size_t i = 0; i < 4; ++i) {
        h1 += 0x9e3779b97f4a7c15ULL;
        UINT64 z = h1;
        z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9ULL;
        z = (z ^ (z >> 27)) * 0x94d049bb133111ebULL;
        z = z ^ (z >> 31);

        for (size_t b = 0; b < 8; ++b) {
            key[i * 8 + b] = static_cast<BYTE>((z >> (b * 8)) & 0xFF);
        }
    }

    return key;
}

String E_XORGenerator::Format_HexBytes(const Array<BYTE> &key) {
    std::ostringstream ss;
    for (size_t i = 0; i < key.size(); ++i) {
        ss << "0x" << std::uppercase << std::hex << std::setw(2) << std::setfill('0') << static_cast<int>(key[i]);
        if (i + 1 < key.size()) ss << ", ";
        if ((i + 1) % 8 == 0 && i + 1 < key.size()) ss << "\n    ";
    }
    return ss.str();
}

String E_XORGenerator::Generate_Header_Source(const String &passphrase, const Array<BYTE> &key) {
    std::ostringstream ss;
    ss << "// ============================================================================\n";
    ss << "// Aurora Engine Project Encryption Key\n";
    ss << "// Auto-generated by Aurora Editor XOR Key Generator\n";
    ss << "// Passphrase: \"" << passphrase << "\"\n";
    ss << "// ============================================================================\n";
    ss << "#pragma once\n\n";
    ss << "#include <U_Variables.h>\n\n";
    ss << "// 256-Bit Cryptographic Keystream for .pak Archive Decryption\n";
    ss << "inline constexpr BYTE AURORA_XOR_KEY[] = {\n    ";
    ss << Format_HexBytes(key);
    ss << "\n};\n\n";
    ss << "inline constexpr size_t AURORA_XOR_KEY_LEN = sizeof(AURORA_XOR_KEY);\n";
    return ss.str();
}

BOOL E_XORGenerator::Save_Header_To_File(const FilePath &outPath, const String &passphrase, const Array<BYTE> &key) {
    String content = Generate_Header_Source(passphrase, key);
    return M_File::Write(outPath, content, /*bOverWrite=*/true);
}
